import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

// Security review of the generated baseline, not an SDK-to-IAM mapper.
// Any source change requires re-running Autopilot and explicitly reviewing
// these deployment assumptions before changing the reviewed digest.
export const REVIEWED_SOURCE_SHA256 = '748722bf9507494c2c0b96e798f927efb4b95f8d1345f9b5c3e8661fb209c2bc';
export const BACKUP_RESOURCE = 'arn:aws:s3:::maptalk-beta-579072312038-us-east-2/maptalk/backups/*';

export const REVIEWED_ACTIONS = Object.freeze({
  'kms:Decrypt': 'exclude: SSE-S3 AES256, not SSE-KMS',
  'kms:GenerateDataKey': 'exclude: SSE-S3 AES256, not SSE-KMS',
  's3:AbortMultipartUpload': 'retain: cancel incomplete encrypted backup upload',
  's3:PutObject': 'retain: upload encrypted backup parts and complete them',
  's3:PutObjectAcl': 'exclude: no ACL header; bucket ownership is bucket-owner-enforced',
  's3:PutObjectLegalHold': 'exclude: no object-lock/legal-hold request',
  's3:PutObjectRetention': 'exclude: no object-lock retention request',
  's3:PutObjectTagging': 'exclude: no object tags; format is ordinary object metadata',
  's3-object-lambda:AbortMultipartUpload': 'exclude: normal S3 bucket, no Object Lambda access point',
  's3-object-lambda:PutObject': 'exclude: normal S3 bucket, no Object Lambda access point',
});

export function refineBackupPolicy(baseline, source) {
  const digest = createHash('sha256').update(source).digest('hex');
  if (digest !== REVIEWED_SOURCE_SHA256) {
    throw new Error('Backup source changed: regenerate Autopilot baseline and review IAM assumptions.');
  }
  if (baseline.Version !== '2012-10-17' || !Array.isArray(baseline.Statement)) {
    throw new Error('Expected an IAM identity policy generated by Autopilot.');
  }
  const generatedActions = new Set();
  for (const statement of baseline.Statement) {
    if (statement.Effect !== 'Allow' || !Array.isArray(statement.Action)
      || !Array.isArray(statement.Resource) || statement.NotAction || statement.NotResource
      || statement.Principal || statement.NotPrincipal) {
      throw new Error('Generated policy shape changed; explicit review required.');
    }
    for (const action of statement.Action) generatedActions.add(action);
  }
  if (generatedActions.size !== Object.keys(REVIEWED_ACTIONS).length
    || [...generatedActions].some(action => !Object.hasOwn(REVIEWED_ACTIONS, action))) {
    throw new Error('Generated action set changed; explicit review required.');
  }

  const statements = baseline.Statement.flatMap(statement => {
    const actions = statement.Action.filter(action => REVIEWED_ACTIONS[action].startsWith('retain:'));
    if (!actions.length) return [];
    if (statement.Condition) throw new Error('Retained baseline conditions changed; explicit review required.');
    return [{ ...statement, Action: actions, Resource: [BACKUP_RESOURCE] }];
  });
  return { Version: baseline.Version, Statement: statements };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const baseline = JSON.parse(readFileSync(new URL('./backup-autopilot-baseline.json', import.meta.url), 'utf8'));
  const source = readFileSync(new URL('../../../src/s3-backup.mjs', import.meta.url));
  process.stdout.write(`${JSON.stringify(refineBackupPolicy(baseline, source), null, 2)}\n`);
}
